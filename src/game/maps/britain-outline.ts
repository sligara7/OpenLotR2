/*
 * Great Britain — coastline outlines (longitude, latitude degrees).
 *
 * Closed rings tracing the coast, taken from Natural Earth's 1:50m
 * `ne_50m_coastline` dataset and simplified (Ramer-Douglas-Peucker) to the
 * detail a hex map can actually show.
 *
 * Natural Earth is in the PUBLIC DOMAIN — no attribution or share-alike
 * obligation — which is why it was chosen over OpenStreetMap's ODbL coastline
 * (design decision: "Rasterise a real coastline as a land mask"). The geography
 * here is fact, not anyone's artwork, so nothing about it strains the project's
 * original-content-only policy.
 *
 * This is the map's SILHOUETTE. `britain-tiles.ts` rasterises these rings to
 * decide which hexes are land, so the island's shape comes from the real coast
 * instead of from where county centres happen to sit — which is what made the
 * old map read as a cluster of bubbles.
 *
 * Only two rings are carried: the Great Britain mainland, and Anglesey, which is
 * a county in its own right and would otherwise have its centre out at sea. Every
 * other offshore island is left out deliberately — no county depends on one.
 *
 * Coordinates are rounded to 3 decimal places (~110 m), far finer than a hex.
 */

