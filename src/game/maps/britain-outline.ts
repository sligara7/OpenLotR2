/**
 * Sea channels too narrow to survive rasterisation.
 *
 * A hex here spans several kilometres, so a strait under a kilometre wide falls
 * entirely between two hex centres and the island on its far side quietly welds
 * itself to the mainland. The Menai Strait is exactly that case: without this,
 * Anglesey stops being an island, the game's only real sea crossing disappears,
 * and the whole ferry system becomes dead code.
 *
 * So the fact is authored back in. Each entry is a line segment the water
 * follows, in [longitude, latitude]; the tile builder floods the land within
 * `widthDeg` of it. Keep this list SHORT and only for water that genuinely
 * exists — it is a correction to the raster, never a way to carve new geography.
 */
export interface Strait {
  readonly name: string;
  readonly from: readonly [number, number];
  readonly to: readonly [number, number];
  /** Half-width in degrees of latitude; a tile centre nearer than this is sea. */
  readonly widthDeg: number;
}

